"""Keep the developer .venv of code_aortic_valve and aortic-seg-infer on the same
package versions.

The shared versions live in constraints.txt next to this project's
requirements.txt. A package that is installed in only one of the two .venv is
fine; a package installed in both must have the version from constraints.txt.

    python tools/sync_envs.py           check both .venv against constraints.txt
    python tools/sync_envs.py update    rewrite constraints.txt from both .venv:
                                        the newer version of each package wins,
                                        exact pins (==) in requirements.txt win
                                        over everything
    python tools/sync_envs.py apply     install the constraints.txt version into
                                        every .venv where it differs

Typical workflow after upgrading or adding a package in one project:
    update -> apply -> check -> commit constraints.txt

Any Python works for running this script: it calls each project's own
.venv\\Scripts\\python -m pip (the pip.exe there may hold an old path).
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent          # code_aortic_valve
VENVS = {
    "code_aortic_valve": ROOT / ".venv",
    "aortic-seg-infer": ROOT.parent / "aortic-seg-infer" / ".venv",
}
CONSTRAINTS = ROOT / "constraints.txt"
REQUIREMENTS = ROOT / "requirements.txt"
# Our own packages (editable / git installs) and packaging tools: not version-locked.
SKIP = {"code-aortic-valve", "morpho-gcn", "pip", "setuptools", "wheel"}

HEADER = """\
# Exact package versions shared by the developer .venv of code_aortic_valve and
# aortic-seg-infer. Generated by tools/sync_envs.py update - edit by hand only
# to pin a specific version, then run tools/sync_envs.py apply.
# Install with constraints:  python -m pip install <pkg> -c constraints.txt
"""


def canon(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def vkey(v):
    """Version sort key without third-party imports (packaging may be absent)."""
    v = v.split("+")[0]
    return [(0, int(p)) if p.isdigit() else (1, p) for p in re.split(r"[.\-]", v)]


def python_of(venv):
    return venv / "Scripts" / "python.exe"


def installed(venv):
    out = subprocess.run(
        [str(python_of(venv)), "-m", "pip", "list", "--format=json", "--disable-pip-version-check"],
        capture_output=True, text=True, check=True,
    ).stdout
    return {canon(p["name"]): p["version"].split("+")[0] for p in json.loads(out)
            if canon(p["name"]) not in SKIP}


def read_pins(path):
    pins = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if "==" in line and "@" not in line:
            name, ver = line.split("==", 1)
            pins[canon(name)] = ver.strip()
    return pins


def existing_venvs():
    found = {k: v for k, v in VENVS.items() if python_of(v).exists()}
    for k in VENVS.keys() - found.keys():
        print(f"[skip] {k}: no .venv at {VENVS[k]}")
    return found


def mismatches(venvs, constraints):
    """{venv: [(name, installed, wanted)]} plus {venv: [names missing from constraints]}."""
    bad, unknown = {}, {}
    for key, venv in venvs.items():
        inst = installed(venv)
        bad[key] = [(n, v, constraints[n]) for n, v in sorted(inst.items())
                    if n in constraints and v != constraints[n]]
        unknown[key] = sorted(n for n in inst if n not in constraints)
    return bad, unknown


def cmd_check():
    if not CONSTRAINTS.exists():
        sys.exit("constraints.txt not found - run: python tools/sync_envs.py update")
    constraints = read_pins(CONSTRAINTS)
    bad, unknown = mismatches(existing_venvs(), constraints)
    ok = True
    for key in bad:
        if bad[key]:
            ok = False
            print(f"\n{key}: {len(bad[key])} package(s) differ from constraints.txt")
            for n, have, want in bad[key]:
                print(f"  {n:32} installed {have:14} constraints {want}")
        if unknown[key]:
            ok = False
            print(f"\n{key}: not in constraints.txt (run update): {', '.join(unknown[key])}")
    print("\nOK: both .venv match constraints.txt" if ok else "\nNOT IN SYNC: run update and/or apply")
    return 0 if ok else 1


def cmd_update():
    merged = {}
    for venv in existing_venvs().values():
        for n, v in installed(venv).items():
            if n not in merged or vkey(v) > vkey(merged[n]):
                merged[n] = v
    pins = read_pins(REQUIREMENTS)
    for n, v in pins.items():
        if n in merged and merged[n] != v:
            print(f"[pin] {n}: {merged[n]} -> {v} (requirements.txt)")
        merged[n] = v
    old = read_pins(CONSTRAINTS) if CONSTRAINTS.exists() else {}
    for n in sorted(merged):
        if old.get(n) != merged[n]:
            print(f"  {n:32} {old.get(n, '-'):14} -> {merged[n]}")
    CONSTRAINTS.write_text(HEADER + "".join(f"{n}=={merged[n]}\n" for n in sorted(merged)),
                           encoding="utf-8")
    print(f"written {CONSTRAINTS} ({len(merged)} packages)")
    return 0


def cmd_apply():
    constraints = read_pins(CONSTRAINTS)
    venvs = existing_venvs()
    bad, _ = mismatches(venvs, constraints)
    for key, items in bad.items():
        if not items:
            print(f"{key}: already in sync")
            continue
        print(f"{key}: installing {len(items)} package(s)")
        subprocess.run(
            [str(python_of(venvs[key])), "-m", "pip", "install", "--disable-pip-version-check",
             "-c", str(CONSTRAINTS), *(f"{n}=={want}" for n, _, want in items)],
            check=True,
        )
    return cmd_check()


if __name__ == "__main__":
    cmds = {"check": cmd_check, "update": cmd_update, "apply": cmd_apply}
    arg = sys.argv[1] if len(sys.argv) > 1 else "check"
    if arg not in cmds:
        sys.exit(__doc__)
    sys.exit(cmds[arg]())
